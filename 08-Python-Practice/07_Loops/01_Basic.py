# Print Number 1 to 10
for i in range(1, 11):
    print(i)


# Print Numbers 1 to 5 using while

i = 1
while i <= 5:
    print(i)
    i += 1

# Print even numbers 1 to 10
for i in range(1, 11):
    if i % 2 == 0:
        print(i) 
# Print odd number 1 to 10
for i in range(1, 11):
    if i % 2 != 0:
        print(i)

# Print the multiplication table of 5

for i in range(1, 11):
    print(5 * i)
    
