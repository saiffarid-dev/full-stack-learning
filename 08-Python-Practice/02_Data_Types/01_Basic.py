# integer (int)
age = 25

print(age)
print(type(age))

# Float (float)

price = 25.66

print(type(price))

# String str

name = "Saif"
print(name)
print(type(name))

# Boolean (bool)

is_student = True

print(is_student)
print(type(is_student))


# Complex (complex)

number = 6 + 4j

print(number)
print(type(number))

# List 

fruits = ["Apple," "Banana", "Mango"]
print(fruits)
print(type(fruits))


# Tuple

colors = ("Red", "Blue", "Green")

print(colors)
print(type(colors))

# Set 

numbers = {10, 20, 30}
print(numbers)

print(type(numbers))


# Dictionary 

student = {
    "name": "Saif",
    "age": 25
}

print(student)
print(type(student))


# None 
result = None

print(result)
print(type(result))